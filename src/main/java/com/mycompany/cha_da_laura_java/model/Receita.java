package com.mycompany.cha_da_laura_java.model;

import java.math.BigDecimal;

public class Receita {

    private int idReceita;
    private int idProduto;
    private String nome;
    private BigDecimal rendimento;
    private String unidadeRendimento;
    private String descricao;
    private boolean ativo;

    public Receita() {
    }

    public int getIdReceita() {
        return idReceita;
    }

    public void setIdReceita(int idReceita) {
        this.idReceita = idReceita;
    }

    public int getIdProduto() {
        return idProduto;
    }

    public void setIdProduto(int idProduto) {
        this.idProduto = idProduto;
    }

    public String getNome() {
        return nome;
    }

    public void setNome(String nome) {
        this.nome = nome;
    }

    public BigDecimal getRendimento() {
        return rendimento;
    }

    public void setRendimento(BigDecimal rendimento) {
        this.rendimento = rendimento;
    }

    public String getUnidadeRendimento() {
        return unidadeRendimento;
    }

    public void setUnidadeRendimento(String unidadeRendimento) {
        this.unidadeRendimento = unidadeRendimento;
    }

    public String getDescricao() {
        return descricao;
    }

    public void setDescricao(String descricao) {
        this.descricao = descricao;
    }

    public boolean isAtivo() {
        return ativo;
    }

    public void setAtivo(boolean ativo) {
        this.ativo = ativo;
    }

    @Override
    public String toString() {
        return nome;
    }
}

